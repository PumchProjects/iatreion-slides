import os
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

from config import CONFIG, Model, ProjectConfig, Unit

MARKER = ".iatreion-merged-unit"


@dataclass(frozen=True)
class Link:
    source: Path
    destination: Path


def model_links(config: ProjectConfig, unit: Unit, model: Model) -> list[Link]:
    download_root = config.downloads_by_id[model.download].local_root
    links: list[Link] = []
    for setting in unit.settings:
        source_setting = download_root / setting
        destination_setting = unit.root / setting
        for group in unit.groups:
            if "external" in unit.validations:
                links.append(
                    Link(
                        source=source_setting / "final" / group / model.name,
                        destination=destination_setting / "final" / group / model.id,
                    )
                )

            if "internal" in unit.validations:
                source_training = (
                    source_setting / "training" / unit.train_name / group
                )
                destination_training = (
                    destination_setting / "training" / unit.train_name / group
                )
                links.extend(
                    (
                        Link(
                            source=source_training / model.name,
                            destination=destination_training / model.id,
                        ),
                        Link(
                            source=source_training / "result-replay" / model.name,
                            destination=(
                                destination_training / "result-replay" / model.id
                            ),
                        ),
                    )
                )
                parser_source = source_training / f"{model.name}-parser"
                if parser_source.exists() or model.name == "rrl":
                    links.append(
                        Link(
                            source=parser_source,
                            destination=destination_training / model.parser_id,
                        )
                    )
    return links


def unit_links(config: ProjectConfig, unit: Unit) -> list[Link]:
    return [link for model in unit.models for link in model_links(config, unit, model)]


def validate_links(links: list[Link]) -> None:
    missing = [link.source for link in links if not link.source.is_dir()]
    if missing:
        paths = "\n".join(f"  - {path}" for path in missing)
        raise FileNotFoundError(f"missing model directories:\n{paths}")

    destinations: set[Path] = set()
    for link in links:
        if link.destination in destinations:
            raise ValueError(f"duplicate merged destination: {link.destination}")
        destinations.add(link.destination)


def validate_existing_root(root: Path) -> None:
    if not root.exists() and not root.is_symlink():
        return
    if root.is_symlink() or not root.is_dir() or not (root / MARKER).is_file():
        raise FileExistsError(f"refusing to replace unmanaged unit root: {root}")


def create_links(temp_root: Path, unit_root: Path, links: list[Link]) -> None:
    (temp_root / MARKER).write_text(
        "Generated by python -m scripts.merge.\n", encoding="utf-8"
    )
    for link in links:
        relative_destination = link.destination.relative_to(unit_root)
        destination = temp_root / relative_destination
        destination.parent.mkdir(parents=True, exist_ok=True)
        relative_source = os.path.relpath(link.source, destination.parent)
        destination.symlink_to(relative_source, target_is_directory=True)


def replace_root(root: Path, temp_root: Path) -> None:
    if not root.exists():
        temp_root.rename(root)
        return

    backup = Path(tempfile.mkdtemp(prefix=f".{root.name}.merge-old-", dir=root.parent))
    backup.rmdir()
    root.rename(backup)
    try:
        temp_root.rename(root)
    except BaseException:
        backup.rename(root)
        raise
    shutil.rmtree(backup)


def merge_unit(config: ProjectConfig, unit: Unit) -> None:
    links = unit_links(config, unit)
    validate_links(links)
    validate_existing_root(unit.root)

    unit.root.parent.mkdir(parents=True, exist_ok=True)
    temp_root = Path(
        tempfile.mkdtemp(prefix=f".{unit.root.name}.merge-", dir=unit.root.parent)
    )
    try:
        create_links(temp_root, unit.root, links)
        replace_root(unit.root, temp_root)
    finally:
        if temp_root.exists():
            shutil.rmtree(temp_root)


def main() -> None:
    if len(sys.argv) != 1:
        raise SystemExit(f"Usage: {sys.argv[0]}")

    for index, unit in enumerate(CONFIG.units, start=1):
        print(f"Merging unit {index}: {unit.root}")
        merge_unit(CONFIG, unit)
    print(f"Merged {len(CONFIG.units)} units")


if __name__ == "__main__":
    main()
